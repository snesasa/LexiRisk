from typing import Dict, Any
from datetime import datetime

class ExportService:
    @staticmethod
    def generate_markdown(contract: Dict[str, Any]) -> str:
        """Generates executive Markdown audit report."""
        title = contract.get('title', 'Contract Risk Analysis')
        score = contract.get('overall_risk_score', 0)
        level = contract.get('risk_level', 'Low')
        date_str = datetime.utcnow().strftime("%B %d, %Y")

        lines = [
            f"# Contract Clause Risk Analysis Report",
            f"**Contract Title:** {title}  ",
            f"**Audit Date:** {date_str}  ",
            f"**Overall Risk Score:** **{score}/100 ({level} Risk)**  ",
            f"**Total Clauses Audited:** {len(contract.get('clauses', []))}  ",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            contract.get('summary', 'Automated clause risk assessment conducted using fine-tuned CUAD legal NLP models and rule-based heuristic auditing.'),
            "",
            "### Risk Statistics",
            f"- **Critical Risk Clauses:** {sum(1 for c in contract.get('clauses', []) if c.get('risk_level') == 'Critical')}",
            f"- **High Risk Clauses:** {sum(1 for c in contract.get('clauses', []) if c.get('risk_level') == 'High')}",
            f"- **Medium Risk Clauses:** {sum(1 for c in contract.get('clauses', []) if c.get('risk_level') == 'Medium')}",
            f"- **Low Risk Clauses:** {sum(1 for c in contract.get('clauses', []) if c.get('risk_level') == 'Low')}",
            f"- **Missing Core Protections:** {len(contract.get('findings', []))}",
            "",
            "---",
            "",
            "## 2. Missing Core Protections & Red Flags",
            ""
        ]

        findings = contract.get('findings', [])
        if findings:
            lines.append("| Severity | Protection | Finding | Suggested Remediation |")
            lines.append("|---|---|---|---|")
            for f in findings:
                lines.append(f"| **{f.get('severity')}** | {f.get('title')} | {f.get('description')} | {f.get('recommendation')} |")
        else:
            lines.append("No critical boilerplate protections were found to be missing.")

        lines.extend([
            "",
            "---",
            "",
            "## 3. Future Dispute Scenarios & Litigation Risks",
            ""
        ])

        scenarios = contract.get('scenarios', [])
        for i, s in enumerate(scenarios, 1):
            lines.extend([
                f"### Scenario {i}: {s.get('title')}",
                f"- **Dispute Type:** {s.get('dispute_type')}",
                f"- **Likelihood:** {s.get('probability')} | **Impact:** {s.get('impact')}",
                f"- **Trigger Event:** {s.get('trigger_event')}",
                f"",
                f"> **Risk Analysis:** {s.get('description')}",
                f"",
                "**Recommended Actionable Mitigations:**"
            ])
            for m in s.get('mitigations', []):
                lines.append(f"- {m}")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 4. Clause-by-Clause Findings & Redlines",
            ""
        ])

        for c in contract.get('clauses', []):
            if c.get('risk_level') in ['Critical', 'High', 'Medium']:
                lines.extend([
                    f"### Clause {c.get('clause_index')}: {c.get('category')} (`{c.get('risk_level')}` Risk - Score: {c.get('risk_score')})",
                    f"**Section Header:** {c.get('section_title')}",
                    "",
                    f"```text\n{c.get('text')}\n```",
                    "",
                    f"**Analysis:** {c.get('explanation')}",
                    "",
                    f"**Actionable Redline Suggestion:**",
                    f"```\n{c.get('redline_suggestion')}\n```",
                    ""
                ])

        lines.extend([
            "---",
            "",
            "> *Legal Disclaimer: This automated report is generated by an AI-assisted analysis tool to accelerate human contract review. It does not constitute formal legal counsel or guarantee judicial enforceability.*"
        ])

        return "\n".join(lines)

    @staticmethod
    def generate_html(contract: Dict[str, Any]) -> str:
        """Generates print-ready, professional HTML report."""
        title = contract.get('title', 'Contract Risk Analysis')
        score = contract.get('overall_risk_score', 0)
        level = contract.get('risk_level', 'Low')
        date_str = datetime.utcnow().strftime("%B %d, %Y")

        badge_color = "#e53e3e" if level == "Critical" else "#dd6b20" if level == "High" else "#d69e2e" if level == "Medium" else "#38a169"

        clauses_html = ""
        for c in contract.get('clauses', []):
            if c.get('risk_level') in ['Critical', 'High', 'Medium']:
                c_badge = "#e53e3e" if c.get('risk_level') == "Critical" else "#dd6b20" if c.get('risk_level') == "High" else "#d69e2e"
                clauses_html += f"""
                <div class="clause-card">
                    <div class="clause-header">
                        <div>
                            <strong>Clause {c.get('clause_index')}: {c.get('category')}</strong>
                            <div class="section-tag">{c.get('section_title', '')}</div>
                        </div>
                        <span class="badge" style="background: {c_badge};">{c.get('risk_level')} ({c.get('risk_score')}/100)</span>
                    </div>
                    <div class="excerpt-box">{c.get('text', '')}</div>
                    <div class="analysis-box"><strong>Finding:</strong> {c.get('explanation', '')}</div>
                    <div class="redline-box"><strong>Proposed Revision:</strong><br>{c.get('redline_suggestion', '')}</div>
                </div>
                """

        scenarios_html = ""
        for s in contract.get('scenarios', []):
            scenarios_html += f"""
            <div class="scenario-card">
                <h4>{s.get('title')}</h4>
                <div class="meta-row">
                    <span><strong>Type:</strong> {s.get('dispute_type')}</span>
                    <span><strong>Likelihood:</strong> {s.get('probability')}</span>
                    <span><strong>Impact:</strong> {s.get('impact')}</span>
                </div>
                <p><strong>Trigger Condition:</strong> {s.get('trigger_event')}</p>
                <p>{s.get('description')}</p>
            </div>
            """

        findings_html = ""
        for f in contract.get('findings', []):
            findings_html += f"""
            <tr>
                <td><span class="badge badge-{f.get('severity', 'High').lower()}">{f.get('severity')}</span></td>
                <td><strong>{f.get('title')}</strong></td>
                <td>{f.get('description')}</td>
                <td>{f.get('recommendation')}</td>
            </tr>
            """

        html = f"""<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>Contract Risk Report - {title}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; line-height: 1.6; color: #1a202c; max-width: 900px; margin: 40px auto; padding: 0 20px; }}
        .header {{ border-bottom: 2px solid #e2e8f0; padding-bottom: 20px; margin-bottom: 30px; display: flex; justify-content: space-between; align-items: center; }}
        .score-pill {{ background: {badge_color}; color: white; padding: 12px 24px; border-radius: 8px; font-weight: bold; font-size: 20px; text-align: center; }}
        h1 {{ margin: 0 0 8px 0; color: #0f172a; font-size: 26px; }}
        h2 {{ color: #1e293b; border-bottom: 1px solid #cbd5e1; padding-bottom: 8px; margin-top: 36px; font-size: 20px; }}
        .badge {{ display: inline-block; padding: 4px 10px; border-radius: 4px; font-size: 12px; font-weight: bold; color: white; }}
        .badge-critical {{ background: #e53e3e; }}
        .badge-high {{ background: #dd6b20; }}
        .badge-medium {{ background: #d69e2e; }}
        .badge-low {{ background: #38a169; }}
        .clause-card {{ border: 1px solid #e2e8f0; border-radius: 8px; padding: 16px; margin-bottom: 18px; background: #fafafa; }}
        .clause-header {{ display: flex; justify-content: space-between; margin-bottom: 10px; }}
        .section-tag {{ font-size: 13px; color: #64748b; }}
        .excerpt-box {{ background: #f1f5f9; padding: 12px; border-left: 4px solid #94a3b8; font-family: monospace; font-size: 13px; white-space: pre-wrap; margin-bottom: 10px; }}
        .analysis-box {{ color: #334155; margin-bottom: 10px; font-size: 14px; }}
        .redline-box {{ background: #eff6ff; border: 1px solid #bfdbfe; color: #1e3a8a; padding: 12px; border-radius: 6px; font-size: 13px; white-space: pre-wrap; }}
        .scenario-card {{ border: 1px solid #fed7aa; background: #fffaf0; border-radius: 8px; padding: 16px; margin-bottom: 16px; }}
        .scenario-card h4 {{ margin: 0 0 8px 0; color: #9a3412; font-size: 16px; }}
        .meta-row {{ font-size: 13px; color: #7c2d12; margin-bottom: 8px; display: flex; gap: 20px; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 14px; font-size: 14px; }}
        th, td {{ border: 1px solid #cbd5e1; padding: 10px; text-align: left; }}
        th {{ background: #f8fafc; font-weight: 600; }}
        .disclaimer {{ margin-top: 50px; font-size: 12px; color: #64748b; border-top: 1px solid #e2e8f0; padding-top: 16px; }}
        @media print {{ body {{ margin: 0; padding: 0; }} }}
    </style>
</head>
<body>
    <div class="header">
        <div>
            <h1>Contract Risk Analysis & Dispute Audit</h1>
            <p style="margin: 0; color: #64748b;">Contract: <strong>{title}</strong> | Date: {date_str}</p>
        </div>
        <div class="score-pill">
            Risk: {score}/100<br><span style="font-size: 14px; font-weight: normal;">{level} Risk</span>
        </div>
    </div>

    <h2>1. Executive Summary</h2>
    <p>{contract.get('summary', 'Automated clause risk assessment conducted using fine-tuned CUAD legal NLP models and rule-based heuristic auditing.')}</p>

    <h2>2. Missing Core Protections Audit</h2>
    <table>
        <thead>
            <tr>
                <th style="width: 100px;">Severity</th>
                <th style="width: 220px;">Provision</th>
                <th>Vulnerability Description</th>
                <th>Recommended Remedy</th>
            </tr>
        </thead>
        <tbody>
            {findings_html if findings_html else '<tr><td colspan="4">No critical protections absent.</td></tr>'}
        </tbody>
    </table>

    <h2>3. Future Scenario Detection & Dispute Forecast</h2>
    {scenarios_html}

    <h2>4. Clause-by-Clause High-Risk Analysis & Redlines</h2>
    {clauses_html}

    <div class="disclaimer">
        Notice: This AI-generated report provides decision support for contract review teams and does not constitute formal legal counsel.
    </div>
</body>
</html>"""
        return html
